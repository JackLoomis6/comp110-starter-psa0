import turtle


screen = turtle.Screen()
screen.bgcolor("lightblue")
t = turtle.Turtle()
t.speed(0)
t.pensize(4)

t.penup()
t.goto(-110, -30)
t.setheading(25)
t.pendown()
t.color("saddlebrown", "peru")
t.begin_fill()
t.circle(115, 120)
t.circle(75, 80)
t.circle(105, 110)
t.circle(65, 90)
t.circle(95, 100)
t.circle(115, 110)
t.end_fill()

t.penup()
t.goto(75, 75)
t.setheading(25)
t.pendown()
t.color("sienna", "tan")
t.begin_fill()
t.circle(42, 180)
t.circle(30, 180)
t.end_fill()

t.penup()
t.goto(102, 82)
t.setheading(90)
t.pendown()
t.color("white", "ivory")
t.begin_fill()
t.circle(18)
t.end_fill()

t.penup()
t.goto(-65, 75)
t.setheading(-25)
t.pendown()
t.color("darkgoldenrod")
t.pensize(6)
t.circle(45, 65)
t.circle(-35, 70)

t.penup()
t.goto(-15, 105)
t.setheading(-30)
t.pendown()
t.circle(35, 70)

t.hideturtle()
turtle.done()
